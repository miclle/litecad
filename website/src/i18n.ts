function createMemoryStorage(): Storage {
  const values = new Map<string, string>()
  return {
    get length() {
      return values.size
    },
    clear() {
      values.clear()
    },
    getItem(key: string) {
      return values.get(key) ?? null
    },
    key(index: number) {
      return Array.from(values.keys())[index] ?? null
    },
    removeItem(key: string) {
      values.delete(key)
    },
    setItem(key: string, value: string) {
      values.set(key, value)
    },
  }
}

function languageStorage() {
  try {
    if (window.localStorage) {
      return window.localStorage
    }
  } catch {
    // Fall through to an in-memory store for test or storage-restricted environments.
  }
  const memoryStorage = createMemoryStorage()
  Object.defineProperty(window, 'localStorage', {
    configurable: true,
    value: memoryStorage,
  })
  return memoryStorage
}

function resolveInitialLanguage(): SupportedLanguage {
  const storedLanguage = languageStorage().getItem('litecad:language')
  if (storedLanguage === 'en' || storedLanguage === 'zh') {
    return storedLanguage
  }

  const browserLanguage = window.navigator.language.toLowerCase()
  return browserLanguage.startsWith('zh') ? 'zh' : 'en'
}

void i18n.use(initReactI18next).init({
  resources,
  lng: resolveInitialLanguage(),
  fallbackLng: 'en',
  supportedLngs: supportedLanguages,
  interpolation: {
    escapeValue: false,
  },
  react: {
    useSuspense: false,
  },
})

i18n.on('languageChanged', (language) => {
  if (language === 'en' || language === 'zh') {
    languageStorage().setItem('litecad:language', language)
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en'
  }
})

document.documentElement.lang = i18n.language === 'zh' ? 'zh-CN' : 'en'

